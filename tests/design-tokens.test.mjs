import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import { execFileSync } from 'node:child_process';
import test from 'node:test';

const css = await readFile(new URL('../src/assets/styles/generated/design-tokens.css', import.meta.url), 'utf8');

function declarations(selector) {
  const block = css.match(new RegExp(`${selector.replace('.', '\\.')} \\{([\\s\\S]*?)\\}`))?.[1];
  assert.ok(block, `Generated CSS is missing ${selector}`);
  return Object.fromEntries([...block.matchAll(/(--[\w-]+):\s*([^;]+);/g)].map(([, key, value]) => [key, value]));
}

function luminance(hex) {
  const channels = hex
    .slice(1)
    .match(/../g)
    .map((value) => Number.parseInt(value, 16) / 255);
  const [r, g, b] = channels.map((value) => (value <= 0.04045 ? value / 12.92 : ((value + 0.055) / 1.055) ** 2.4));
  return 0.2126 * r + 0.7152 * g + 0.0722 * b;
}

function contrast(foreground, background) {
  const [lighter, darker] = [luminance(foreground), luminance(background)].sort((a, b) => b - a);
  return (lighter + 0.05) / (darker + 0.05);
}

await test('design tokens regenerate without drift', () => {
  execFileSync('node', ['scripts/build-design-tokens.mjs', '--check'], { stdio: 'pipe' });
  assert.match(css, /GENERATED by scripts\/build-design-tokens\.mjs/);
  assert.match(css, /\.dark\s*\{/);
  assert.doesNotMatch(css, /(--[\w-]+):\s*var\(\1\)/);
});

await test('semantic modes expose the same roles and sharp border geometry', () => {
  const light = declarations(':root');
  const dark = declarations('.dark');
  assert.deepEqual(Object.keys(light).sort(), Object.keys(dark).sort());
  for (const name of [
    '--gg-color-canvas',
    '--gg-color-surface',
    '--gg-color-brand',
    '--gg-color-link',
    '--gg-color-field',
    '--gg-color-field-border',
    '--gg-border-color-focus',
  ]) {
    assert.ok(light[name], `Light theme missing ${name}`);
    assert.ok(dark[name], `Dark theme missing ${name}`);
  }
  for (const name of ['--gg-radius-control', '--gg-radius-surface', '--gg-radius-badge']) {
    assert.equal(light[name], '0px', `Light ${name} must stay square`);
    assert.equal(dark[name], '0px', `Dark ${name} must stay square`);
  }
  assert.equal(light['--gg-border-structural-width'], '2px');
  assert.equal(light['--gg-border-card-width'], '1px');
  assert.equal(light['--gg-border-featured-width'], '2px');
  assert.equal(light['--gg-border-focus-width'], '2px');
});

await test('documented foreground and UI pairings meet WCAG AA thresholds', () => {
  const themes = { light: declarations(':root'), dark: declarations('.dark') };
  const pairs = [
    ['primary CTA', '--gg-color-on-brand', '--gg-color-brand', 4.5],
    ['CTA hover', '--gg-color-on-brand', '--gg-color-brand-hover', 4.5],
    ['CTA pressed', '--gg-color-on-brand', '--gg-color-brand-active', 4.5],
    ['body text on canvas', '--gg-color-text-body', '--gg-color-canvas', 4.5],
    ['muted text on surface', '--gg-color-text-muted', '--gg-color-surface', 4.5],
    ['field text', '--gg-color-field-text', '--gg-color-field', 4.5],
    ['placeholder text', '--gg-color-placeholder', '--gg-color-field', 4.5],
    ['disabled text', '--gg-color-disabled', '--gg-color-disabled-surface', 4.5],
    ['link on canvas', '--gg-color-link', '--gg-color-canvas', 4.5],
    ['link hover on canvas', '--gg-color-link-hover', '--gg-color-canvas', 4.5],
    ['selected state', '--gg-color-on-brand', '--gg-color-brand-active', 4.5],
    ['selection text', '--gg-color-selection-text', '--gg-color-selection', 4.5],
    ['feedback success', '--gg-color-feedback-success', '--gg-color-feedback-success-surface', 4.5],
    ['feedback warning', '--gg-color-feedback-warning', '--gg-color-feedback-warning-surface', 4.5],
    ['feedback error', '--gg-color-feedback-error', '--gg-color-feedback-error-surface', 4.5],
    ['feedback info', '--gg-color-feedback-info', '--gg-color-feedback-info-surface', 4.5],
    ['focus indicator on field', '--gg-border-color-focus', '--gg-color-field', 3],
    ['field boundary on field', '--gg-border-color-component', '--gg-color-field', 3],
    ['structural border on canvas', '--gg-border-color-structural', '--gg-color-canvas', 3],
  ];
  for (const [mode, tokens] of Object.entries(themes)) {
    for (const [pair, foreground, background, threshold] of pairs) {
      const ratio = contrast(tokens[foreground], tokens[background]);
      assert.ok(
        ratio >= threshold,
        `${mode} ${pair}: ${foreground} ${tokens[foreground]} on ${background} ${tokens[background]} measured ${ratio.toFixed(2)}:1; expected >= ${threshold}:1`
      );
    }
  }
});

await test('compatibility aliases use semantic values and do not define generated names recursively', async () => {
  const styles = await readFile(new URL('../src/components/CustomStyles.astro', import.meta.url), 'utf8');
  const tailwind = await readFile(new URL('../src/assets/styles/tailwind.css', import.meta.url), 'utf8');
  const shadcn = await readFile(new URL('../src/assets/styles/shadcn.css', import.meta.url), 'utf8');
  assert.match(styles, /--aw-color-primary:\s*var\(--gg-color-brand\)/);
  assert.match(styles, /--aw-color-text-heading:\s*var\(--gg-color-text-heading\)/);
  assert.match(tailwind, /@theme inline\s*\{/);
  assert.match(tailwind, /@import '\.\/generated\/design-tokens\.css'/);
  assert.match(tailwind, /--color-slate-900:\s*var\(--gg-color-canvas-dark\)/);
  assert.match(tailwind, /--color-gray-500:\s*var\(--gg-color-text-muted\)/);
  assert.match(shadcn, /--radius:\s*0px/);
  assert.match(shadcn, /@theme inline\s*\{/);
});

await test('theme runtime keeps the .dark contract and tolerates blocked storage', async () => {
  const apply = await readFile(new URL('../src/components/common/ApplyColorMode.astro', import.meta.url), 'utf8');
  const toggle = await readFile(new URL('../src/components/common/ToggleTheme.astro', import.meta.url), 'utf8');
  assert.match(apply, /document\.documentElement\.classList/);
  assert.match(apply, /astro:after-swap/);
  assert.match(apply, /prefers-color-scheme:\s*dark/);
  assert.match(apply, /getItem\('theme'\)[\s\S]*?catch/);
  assert.match(toggle, /setItem\('theme'[\s\S]*?catch/);
  assert.doesNotMatch(apply, /data-theme/);
});
